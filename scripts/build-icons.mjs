// Offline, deterministic packaging of the reviewed upstream SVG subset.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const directory = new URL('../assets/design-lab/dist/vendor/lucide/', import.meta.url);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

export async function buildIcons() {
  const manifest = JSON.parse(await readFile(new URL('manifest.json', directory), 'utf8'));
  assert.match(manifest.commit, /^[a-f0-9]{40}$/);
  const license = await readFile(new URL('LICENSE', directory));
  assert.equal(hash(license), manifest.files.find(file => file.file === 'LICENSE').sha256, 'Upstream license changed');
  const markup = {};
  for (const [alias, name] of Object.entries(manifest.mapping)) {
    assert.match(alias, /^[a-z]+$/);
    assert.match(name, /^[a-z]+(?:-[a-z]+)*$/);
    const file = `icons/${name}.svg`;
    const bytes = await readFile(new URL(file, directory));
    assert.equal(hash(bytes), manifest.files.find(entry => entry.file === file)?.sha256, file);
    const match = bytes.toString('utf8').match(/^<svg\b([^>]*)>([\s\S]*?)<\/svg>\s*$/);
    assert.ok(match, `Expected a standalone SVG: ${file}`);
    assert.match(match[1], /viewBox="0 0 24 24"/);
    // Only reviewed, inert drawing primitives. Never insert external SVG markup unchecked.
    const primitives = match[2].match(/<(?:path|rect|circle)\b[^>]*\/>/g) || [];
    assert.ok(primitives.length && match[2].replace(/<(?:path|rect|circle)\b[^>]*\/>/g, '').trim() === '', file);
    for (const primitive of primitives) {
      const attributes = primitive.replace(/^<\w+\s*/, '').replace(/\s*\/>$/, '');
      assert.equal(attributes.replace(/(?:d|x|y|width|height|rx|ry|cx|cy|r)="[a-zA-Z0-9., +\-]*"\s*/g, ''), '', `Unexpected SVG attribute: ${file}`);
    }
    markup[alias] = primitives.join('');
  }
  return `// Generated by scripts/build-icons.mjs. Do not edit drawing data here.\n// Lucide ${manifest.commit}; ISC + applicable Feather MIT notices.\n// Keep the complete adjacent LICENSE and manifest.json when redistributing.\n// Original geometry retained; outer SVG uses the existing Modern 95 UI CSS.\nexport const icons = Object.freeze(${JSON.stringify(markup, null, 2)});\nexport const icon = name => \`<svg class="icon" viewBox="0 0 24 24" aria-hidden="true">\${icons[Object.hasOwn(icons, name) ? name : 'window']}</svg>\`;\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const target = new URL('icons.mjs', directory);
  await writeFile(target, await buildIcons());
  console.log(`Built ${fileURLToPath(target)}`);
}
